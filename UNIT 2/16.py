#P_6 Write a program to iterate over lists strings and dictionaries using loops.

#list
Fruits =["Apple","Banana","Mango"]

print("List:")
for i in Fruits:
    print(i)

#string
name="Palak"
print("string:")
for i in name:
        print(i)


#dictionary

student={"Name":"Palak",
                 "Age":21,
                 "City":"Rajkot"}

for key in student:
    print(key,":",student[key])

    
