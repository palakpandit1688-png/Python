#P_5 Write a program to demonstrate the use of break continue and pass statements.

#break
for i in range(1,6):
    if i==3:
        break
    print(i)

#continue
for i in range(1,6):
    if i==2:
        continue
    print(i)

#pass statement
for i in range(1,6):
    if i==3:
        pass
    print(i)
